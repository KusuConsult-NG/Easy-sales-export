/**
 *   #538 EVERY BADGE IN THE APP POLLED FOREVER, INCLUDING IN TABS NOBODY WAS
 *        LOOKING AT.
 *
 *   Raised by the owner as "the users app is also very slow". It is, and this is
 *   the largest single reason.
 *
 *   Eleven components and hooks hand-rolled the same block — `load()` then
 *   `setInterval(load, 8000)` — and not one asked whether the tab was visible.
 *   A dashboard is a thing people leave open in a background tab, so the app
 *   kept issuing server actions at full rate for as long as the browser stayed
 *   open. Each one re-checks the session, which is a read of the user row
 *   whenever Redis is unset.
 *
 *   MEASURED PER SCREEN, IDLE, DOING NOTHING:
 *
 *     /dashboard   DashboardNav's three pollers (8s, 8s, 10s) plus the page's
 *                  own getMyDashboard (8s, eight queries inside it)
 *                  ≈ 28 server actions and ~75 database queries a minute
 *     /messages    the two nav pollers plus conversations (8s) and messages
 *                  (3s) ≈ 42 server actions a minute
 *     module pages ModuleSidebar (8s), the NotificationCenter inside it (10s)
 *                  and useMembershipStatus (8s) ≈ 21 a minute
 *
 *   AND IT IS THE AUDIT'S USUAL SHAPE UNDERNEATH. getMyDashboard already
 *   returns serviceRegistrations, unreadMessages AND unreadNotifications —
 *   which are exactly the three things DashboardNav polls separately. On
 *   /dashboard all three were fetched twice every eight seconds. That
 *   duplication is recorded here and NOT yet fixed; it needs shared state
 *   between a layout and a page, which is a larger change than this one.
 *
 * ── WHAT IS FIXED ───────────────────────────────────────────────────────────
 *
 *   One primitive, `startVisibilityAwareInterval`, and the `usePolling` hook on
 *   top of it. A hidden tab stops entirely; becoming visible again runs the
 *   task immediately and resumes. So a returning user sees FRESHER data than
 *   before, not staler — previously they saw whatever the last tick left, up to
 *   a full interval old.
 *
 *   Everything moved onto it is a DISPLAY value: an unread count, a badge, a
 *   membership status, a list of registrations. No writes, and nothing
 *   downstream depends on a poll having happened while nobody was looking.
 *
 * ── NOT CLAIMED ─────────────────────────────────────────────────────────────
 *
 *   This does not make the app fast. It removes the load generated by tabs
 *   nobody is looking at, and leaves the foreground rate exactly as it was.
 *   The duplicate-fetch finding above, the 3s message poll, and the fact that
 *   139 of 167 user-facing pages are client components that fetch only after
 *   hydration, are all still open.
 *
 *   MUTATION-TESTED, WITH A CONTROL. Against a green baseline:
 *
 *     the hidden check inverted                        KILLED (8 tests)
 *     the visibilitychange listener never registered   KILLED (1)
 *     the catch-up run on becoming visible removed     KILLED (1)
 *     `immediate: false` ignored                       KILLED (1)
 *     cleanup stops removing the listener              KILLED (1)
 *     one debt-ledger path falsified                   KILLED (3)
 *     the tick's own visibility guard removed          SURVIVED at first —
 *                                                      see below — then KILLED
 *     reword the hook's header                         SURVIVED, as intended
 *
 *   THE SURVIVOR IS THE INTERESTING ONE, AND IT IS RECORDED RATHER THAN
 *   TIDIED AWAY. Deleting the `if (isVisible())` inside the interval tick
 *   changed no result, because every other test reaches the hidden state by
 *   FIRING visibilitychange — which stops the timer by a different route, so
 *   the guard is never the thing under test. The suite was asserting the
 *   listener's behaviour twice and the guard's not at all.
 *
 *   The guard is not redundant: a tab can become hidden without the event
 *   arriving. So the missing test was written rather than the claim softened,
 *   and it is the only one that hides the tab WITHOUT dispatching.
 */

import { describe, it, expect, beforeEach, afterEach, jest } from '@jest/globals';
import { readFileSync, readdirSync, statSync, existsSync } from 'fs';
import { join } from 'path';
import { renderHook } from '@testing-library/react';
import { stripComments } from '@/lib/testing/strip-comments';
import { usePolling, startVisibilityAwareInterval } from '@/hooks/usePolling';

const ROOT = process.cwd();

/**
 * jsdom reports visibilityState from the document, and it is not writable by
 * assignment, so it is redefined. Firing the event separately is deliberate:
 * the production bug is precisely that nothing LISTENED, so a test that only
 * flipped the value would pass against the unfixed code.
 */
function setVisibility(state: 'visible' | 'hidden'): void {
    Object.defineProperty(document, 'visibilityState', {
        configurable: true,
        get: () => state,
    });
    document.dispatchEvent(new Event('visibilitychange'));
}

beforeEach(() => {
    jest.useFakeTimers();
    setVisibility('visible');
});

afterEach(() => {
    jest.useRealTimers();
});

// ─────────────────────────────────────────────────────────────────────────────
describe('#538 — the primitive', () => {
    it('POLLS WHILE THE TAB IS VISIBLE', () => {
        const task = jest.fn<() => void>();
        const stop = startVisibilityAwareInterval(task, 1000);

        expect(task).toHaveBeenCalledTimes(1);   // the immediate run
        jest.advanceTimersByTime(3000);
        expect(task).toHaveBeenCalledTimes(4);

        stop();
    });

    it('AND STOPS COMPLETELY ONCE THE TAB IS HIDDEN', () => {
        //   THE test. Before the fix this kept counting.
        const task = jest.fn<() => void>();
        const stop = startVisibilityAwareInterval(task, 1000);
        task.mockClear();

        setVisibility('hidden');
        jest.advanceTimersByTime(60_000);

        expect(task).not.toHaveBeenCalled();
        stop();
    });

    it('AND CATCHES UP THE MOMENT IT IS LOOKED AT AGAIN', () => {
        //   A pause that did not catch up would show a badge up to one whole
        //   interval stale on return — worse than the behaviour it replaces.
        const task = jest.fn<() => void>();
        const stop = startVisibilityAwareInterval(task, 10_000);
        setVisibility('hidden');
        jest.advanceTimersByTime(60_000);
        task.mockClear();

        setVisibility('visible');

        expect(task).toHaveBeenCalledTimes(1);
        stop();
    });

    it('AND RESUMES THE INTERVAL, NOT JUST THE ONE CATCH-UP', () => {
        //   The vacuity guard: a fix that caught up once and never restarted
        //   the timer passes the test above and silently freezes every badge.
        const task = jest.fn<() => void>();
        const stop = startVisibilityAwareInterval(task, 1000);
        setVisibility('hidden');
        jest.advanceTimersByTime(5000);
        setVisibility('visible');
        task.mockClear();

        jest.advanceTimersByTime(3000);

        expect(task).toHaveBeenCalledTimes(3);
        stop();
    });

    it('AND HONOURS immediate:false for a caller that already loaded once', () => {
        //   /dashboard kicks off its own first load, so running here as well
        //   would double every mount of the most expensive poller in the app.
        const task = jest.fn<() => void>();
        const stop = startVisibilityAwareInterval(task, 1000, { immediate: false });

        expect(task).not.toHaveBeenCalled();
        jest.advanceTimersByTime(1000);
        expect(task).toHaveBeenCalledTimes(1);

        stop();
    });

    it('AND STOPS EVEN IF THE BROWSER NEVER FIRES visibilitychange', () => {
        //   The belt-and-braces guard inside the tick, which exists because a
        //   tab can become hidden without the event arriving — a browser that
        //   throttles a background tab rather than dispatching, or an event
        //   swallowed while the page was mid-navigation.
        //
        //   THIS TEST WAS MISSING AND THE MUTANT SURVIVED. Deleting the guard
        //   changed no result, because every other test reaches hidden state by
        //   firing the event, which stops the timer by another route. So the
        //   only assertion that could ever distinguish them is this one: hide
        //   the tab WITHOUT telling anybody.
        const task = jest.fn<() => void>();
        const stop = startVisibilityAwareInterval(task, 1000);
        task.mockClear();

        Object.defineProperty(document, 'visibilityState', {
            configurable: true,
            get: () => 'hidden',
        });
        // Deliberately NO dispatchEvent here.
        jest.advanceTimersByTime(30_000);

        expect(task).not.toHaveBeenCalled();
        stop();
    });

    it('AND STOPS FOR GOOD WHEN CLEANED UP, LISTENER INCLUDED', () => {
        //   A cleanup that cleared the timer but left the listener attached
        //   would resurrect a dead component's poll on the next tab focus.
        const task = jest.fn<() => void>();
        const stop = startVisibilityAwareInterval(task, 1000);
        stop();
        task.mockClear();

        jest.advanceTimersByTime(10_000);
        setVisibility('hidden');
        setVisibility('visible');
        jest.advanceTimersByTime(10_000);

        expect(task).not.toHaveBeenCalled();
    });
});

