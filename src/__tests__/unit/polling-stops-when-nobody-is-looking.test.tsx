describe('#538 — the hook', () => {
    it('does nothing at all while disabled', () => {
        //   Every caller passes `enabled: !!userId`. A signed-out visitor must
        //   not poll a session-scoped action at all.
        const task = jest.fn<() => void>();
        renderHook(() => usePolling(task, 1000, { enabled: false }));

        jest.advanceTimersByTime(10_000);
        expect(task).not.toHaveBeenCalled();
    });

    it('polls while enabled, and pauses with the tab', () => {
        const task = jest.fn<() => void>();
        renderHook(() => usePolling(task, 1000));

        jest.advanceTimersByTime(2000);
        const whileVisible = task.mock.calls.length;
        expect(whileVisible).toBeGreaterThan(1);

        setVisibility('hidden');
        jest.advanceTimersByTime(30_000);

        expect(task).toHaveBeenCalledTimes(whileVisible);
    });

    it('calls the LATEST closure, not the one from the first render', () => {
        //   The reason the task lives in a ref. If the interval captured the
        //   first render's closure, a badge would keep writing to stale state.
        const first = jest.fn<() => void>();
        const second = jest.fn<() => void>();
        const { rerender } = renderHook(
            ({ fn }: { fn: () => void }) => usePolling(fn, 1000),
            { initialProps: { fn: first } },
        );
        first.mockClear();

        rerender({ fn: second });
        jest.advanceTimersByTime(2000);

        expect(second).toHaveBeenCalled();
        expect(first).not.toHaveBeenCalled();
    });

    it('RESTARTS AND REFETCHES WHEN THE IDENTITY CHANGES', () => {
        //   The counterpart to the test below. The poll must NOT restart on
        //   every render, but it MUST restart when the thing being polled
        //   about changes — the signed-in user, the module being asked about.
        //
        //   THIS WAS A REGRESSION I INTRODUCED AND #416'S SUITE CAUGHT IT. The
        //   first version keyed the effect on the interval alone, so after a
        //   user change the timer survived and the badge went on showing the
        //   PREVIOUS user's count until the next tick.
        const task = jest.fn<() => void>();
        const { rerender } = renderHook(
            ({ id }: { id: string }) => usePolling(task, 10_000, { restartKey: id }),
            { initialProps: { id: 'user-1' } },
        );
        task.mockClear();

        rerender({ id: 'user-2' });

        expect(task).toHaveBeenCalledTimes(1);
    });

    it('does NOT restart the interval on every render', () => {
        //   If the task were in the dependency array, each poll would set state,
        //   re-render, and rebuild the timer — so the true period would drift
        //   and, with a fast enough render, never fire at all.
        const task = jest.fn<() => void>();
        const { rerender } = renderHook(() => usePolling(task, 1000));
        task.mockClear();

        for (let i = 0; i < 5; i++) {
            rerender();
            jest.advanceTimersByTime(200);
        }

        //   1000ms of total elapsed time across five renders = exactly one tick.
        expect(task).toHaveBeenCalledTimes(1);
    });
});

