describe('#538 — no poller goes back to a bare setInterval', () => {
    /**
     * Polling sites that are NOT server round-trips, and so have no reason to
     * pause: animation and countdown timers driven entirely in the browser, a
     * camera scan loop, a session-timeout clock that must keep counting while
     * the tab is hidden precisely because that is when a session lapses.
     *
     * Named rather than pattern-matched, so adding one is a deliberate act.
     */
    const NOT_SERVER_POLLS = new Set([
        'src/components/ui/ImageSlider.tsx',
        'src/components/features/HeroSlider.tsx',
        'src/components/hub/HubHero.tsx',
        'src/components/hub/PlatformStats.tsx',
        'src/components/CountdownTimer.tsx',
        'src/components/auth/SessionActivityTracker.tsx',
        'src/components/DeploymentWatcher.tsx',
        'src/components/lms/VideoPlayer.tsx',
        'src/hooks/usePolling.ts',
        'src/app/verify-id/page.tsx',
        'src/app/wave/landing/page.tsx',
        'src/app/cooperatives/payment/callback/page.tsx',
        'src/app/academy/[courseId]/quiz/[moduleId]/page.tsx',
    ]);

    /**
     * The sites that DO fetch from the server on a timer and have not been
     * moved onto the shared primitive yet.
     *
     * This list is a DEBT LEDGER, not permission. Each one still polls a
     * background tab; they are listed so the number is visible and can only go
     * down — adding to it is a deliberate act, and the test below proves the
     * sweep can still fail.
     */
    const STILL_HAND_ROLLED = new Set([
        'src/app/messages/page.tsx',
        'src/app/escrow/[id]/chat/page.tsx',
        'src/app/dashboard/disputes/page.tsx',
        'src/app/dashboard/notifications/page.tsx',
        'src/app/wave/(member)/live-training/page.tsx',
        //   Admin screens. Same defect, smaller blast radius — a handful of
        //   staff rather than every member — so they are recorded and left for
        //   the admin pass rather than changed in a user-facing fix.
        'src/app/admin/messages/page.tsx',
        'src/app/admin/academy/live/[courseId]/page.tsx',
        'src/app/admin/wave/training/live/[eventId]/page.tsx',
    ]);

    function filesWithBareInterval(): string[] {
        const found: string[] = [];
        const walk = (dir: string) => {
            for (const e of readdirSync(dir)) {
                const full = join(dir, e);
                if (statSync(full).isDirectory()) {
                    if (e !== '__tests__' && e !== 'node_modules') walk(full);
                } else if (/\.tsx?$/.test(e)) {
                    const src = stripComments(readFileSync(full, 'utf-8'), { label: full });
                    if (/setInterval\s*\(/.test(src)) found.push(full.slice(ROOT.length + 1));
                }
            }
        };
        walk(join(ROOT, 'src'));
        return found.sort();
    }

    it('THE SIX ALWAYS-MOUNTED POLLERS USE THE SHARED PRIMITIVE', () => {
        //   These are the ones every signed-in user pays for on every screen.
        const CONVERTED = [
            'src/components/dashboard/DashboardNav.tsx',
            'src/components/layout/ModuleSidebar.tsx',
            'src/components/layout/NotificationCenter.tsx',
            'src/components/layout/Sidebar.tsx',
            'src/hooks/useMembershipStatus.ts',
            'src/hooks/useUnreadNotifications.ts',
        ];
        for (const f of CONVERTED) {
            const src = stripComments(readFileSync(join(ROOT, f), 'utf-8'), { label: f });
            expect({ f, usesHook: /usePolling\s*\(/.test(src) }).toEqual({ f, usesHook: true });
            expect({ f, bareInterval: /setInterval\s*\(/.test(src) }).toEqual({ f, bareInterval: false });
        }
    });

    it('AND THE DASHBOARD PAGE — the most expensive one — USES THE PRIMITIVE', () => {
        const src = stripComments(
            readFileSync(join(ROOT, 'src/app/dashboard/page.tsx'), 'utf-8'),
            { label: 'dashboard' },
        );
        expect(src).toContain('startVisibilityAwareInterval(');
        expect(/setInterval\s*\(/.test(src)).toBe(false);
    });

    it('AND NO NEW HAND-ROLLED POLLER HAS APPEARED', () => {
        const unaccounted = filesWithBareInterval()
            .filter(f => !NOT_SERVER_POLLS.has(f) && !STILL_HAND_ROLLED.has(f));

        expect(unaccounted).toEqual([]);
    });

    it('AND THE SWEEP CAN STILL FAIL — every listed file exists', () => {
        //   #484's shape: a list of paths that no longer exist would silence the
        //   sweep while reading as deliberate.
        for (const f of [...NOT_SERVER_POLLS, ...STILL_HAND_ROLLED]) {
            expect({ f, exists: existsSync(join(ROOT, f)) }).toEqual({ f, exists: true });
        }
    });

    it('AND THE DEBT LEDGER IS HONEST — each listed file really does poll', () => {
        //   A file parked in STILL_HAND_ROLLED that no longer has a setInterval
        //   is debt that was quietly paid; it should leave the list, not sit on
        //   it looking like outstanding work.
        const actuallyPolling = new Set(filesWithBareInterval());
        for (const f of STILL_HAND_ROLLED) {
            expect({ f, polls: actuallyPolling.has(f) }).toEqual({ f, polls: true });
        }
    });
});
